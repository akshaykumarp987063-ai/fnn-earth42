const now = Date.now();
const iso = (minsAgo: number) => new Date(now - minsAgo * 60_000).toISOString();

function tl(labels: TimelineEntry["label"][], startMinsAgo: number): TimelineEntry[] {
  return labels.map((label, i) => ({
    id: `tl-${label}-${i}`,
    label,
    at: iso(Math.max(0, startMinsAgo - i)),
    done: true,
  }));
}

